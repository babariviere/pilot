/** Offline streaming checkpoint comparison: a faux model streams one reply at a steady token rate through the
 * Harness on SQLite, with progress.partialIntervalMs at 250 ms (current) and 100 ms. Reports what a client sees
 * (message_update count, gaps and characters per update) and what it costs (commits, WAL bytes, CPU, event-loop
 * delay). No user resources, credentials or network.
 *
 *   node packages/kernel/scripts/bench-streaming-checkpoints.ts [seconds=15] [tokensPerSecond=100]
 */
import { mkdtemp, rm, stat } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { monitorEventLoopDelay, performance } from "node:perf_hooks";
import { BACKGROUND_CONTEXT as context } from "@earendil-works/chord/context";
import {
	fauxAssistantMessage,
	fauxProvider,
	InMemoryCredentialStore,
	InMemoryModelsStore,
} from "@earendil-works/pi-ai";
import { ModelRuntime, SettingsManager } from "@earendil-works/pi-coding-agent";
import { createRegistry, Harness, UserEntry, watchEvents } from "@earendil-works/pi-durable";
import { openNodeSqliteStorage } from "@earendil-works/pi-durable/storage/sqlite/node";
import { NativeAdapter } from "../src/native-adapter.ts";

globalThis.fetch = async () => {
	throw new Error("Offline benchmark must not access the network");
};

const seconds = Number(process.argv[2] ?? 15);
const tokensPerSecond = Number(process.argv[3] ?? 100);
const tokenSize = 4;
const reply = "Streaming words arrive steadily. ".repeat(Math.ceil((seconds * tokensPerSecond * tokenSize) / 33));

function percentile(values: number[], p: number) {
	if (values.length === 0) return 0;
	const sorted = [...values].sort((a, b) => a - b);
	return sorted[Math.min(sorted.length - 1, Math.floor((sorted.length * p) / 100))]!;
}

for (const interval of [250, 100, 100, 250]) {
	const home = await mkdtemp(join(tmpdir(), "pilot-checkpoint-bench-"));
	const histogram = monitorEventLoopDelay({ resolution: 10 });
	let adapter: NativeAdapter | undefined;
	let harness: Harness | undefined;
	try {
		const models = await ModelRuntime.create({
			credentials: new InMemoryCredentialStore(),
			modelsPath: null,
			modelsStore: new InMemoryModelsStore(),
			allowModelNetwork: false,
			refreshOnCreate: false,
		});
		const faux = fauxProvider({
			provider: "offline-checkpoints",
			models: [{ id: "fixture", contextWindow: 2_000_000 }],
			tokensPerSecond,
			tokenSize: { min: tokenSize, max: tokenSize },
		});
		models.registerNativeProvider(faux.provider);
		const agentDir = join(home, "agent");
		adapter = await NativeAdapter.open({
			cwd: home,
			agentDir,
			// Bundled extensions such as durable subagents anchor their storage beside a session file.
			sessionFile: join(home, "native-session.jsonl"),
			projectTrusted: false,
			settingsManager: SettingsManager.inMemory({ defaultTools: [] }),
			sessionOptions: { modelRuntime: models, model: faux.getModel(), customTools: [] },
			loaderOptions: {
				cwd: home,
				agentDir,
				noExtensions: true,
				noSkills: true,
				noPromptTemplates: true,
				noThemes: true,
				noContextFiles: true,
				systemPrompt: "Offline benchmark",
				appendSystemPrompt: [],
			},
		});
		const registry = createRegistry();
		registry.install(adapter.extension);
		const file = join(home, "session.sqlite");
		// Keep appended WAL frames countable instead of reused. Generated bytes, not device throughput.
		const storage = await openNodeSqliteStorage(file, { walAutoCheckpointPages: 100_000 });
		harness = await Harness.open(
			storage,
			{
				models: adapter.models,
				registry,
				settings: {
					toolExecution: "sequential",
					progress: { partialIntervalMs: interval, outputIntervalMs: interval },
				},
			},
			context,
		);
		const conversation = await harness.root(context, {
			agent: { model: adapter.model, extensions: [adapter.extension], tools: null },
		});
		await conversation.commit(async (tx) => {
			for (let i = 0; i < 1000; i++)
				await tx.appendEntry(UserEntry, conversation.id, {
					model: [{ role: "user", content: `History ${i}: ${"x".repeat(256)}`, timestamp: i }],
				});
		}, context);
		await adapter.bindHarness(harness, conversation.id);
		faux.setResponses([fauxAssistantMessage(reply)]);
		const updates: { at: number; chars: number }[] = [];
		const stream = await watchEvents(harness, conversation.id, context);
		stream.start(async (events) => {
			for (const event of events) {
				if (event.type !== "message_update") continue;
				let chars = 0;
				for (const change of event.changes) {
					if (change.type === "text_delta") chars += change.delta.length;
					else if ("block" in change && change.block?.type === "text") chars += change.block.text.length;
				}
				updates.push({ at: performance.now(), chars });
			}
		});
		const walBefore = (await stat(`${file}-wal`)).size;
		globalThis.gc?.();
		histogram.enable();
		const cpu = process.cpuUsage();
		const start = performance.now();
		await conversation.submit({ type: "input", requestId: "bench", content: "Stream the fixture" }, context);
		await conversation.waitForIdle(context);
		const elapsed = performance.now() - start;
		const used = process.cpuUsage(cpu);
		histogram.disable();
		const walBytes = (await stat(`${file}-wal`)).size - walBefore;
		await stream.stop();
		const gaps = updates.slice(1).map((update, index) => update.at - updates[index]!.at);
		const chars = updates.map((update) => update.chars).filter((count) => count > 0);
		console.log(
			JSON.stringify({
				partialIntervalMs: interval,
				replyChars: reply.length,
				streamSeconds: +(elapsed / 1000).toFixed(1),
				updates: updates.length,
				updatesPerSecond: +(updates.length / (elapsed / 1000)).toFixed(1),
				gapMs: {
					p50: Math.round(percentile(gaps, 50)),
					p95: Math.round(percentile(gaps, 95)),
					max: Math.round(Math.max(0, ...gaps)),
				},
				charsPerUpdate: { p50: percentile(chars, 50), p95: percentile(chars, 95), max: Math.max(0, ...chars) },
				walBytes,
				walKiBPerSecond: +(walBytes / 1024 / (elapsed / 1000)).toFixed(1),
				cpuMs: Math.round((used.user + used.system) / 1000),
				cpuPercent: +(((used.user + used.system) / 1000 / elapsed) * 100).toFixed(1),
				eventLoopP99Ms: +(histogram.percentile(99) / 1e6).toFixed(1),
			}),
		);
	} finally {
		await harness?.close(context);
		await adapter?.close();
		await rm(home, { recursive: true, force: true });
	}
}
